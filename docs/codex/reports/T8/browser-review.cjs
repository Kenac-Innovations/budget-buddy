// eslint-disable-next-line @typescript-eslint/no-unused-expressions
async (page) => {
  const root = '/Users/kudzaimacheyo/VSCProjects/budget-buddy-agents/T8/docs/codex/reports/T8';
  const review = new URL(page.url()).searchParams.get('review') || 'desktop-light';
  const phone = review.startsWith('phone');
  const dark = review.endsWith('dark');
  const browser = page.context().browser();
  const context = await browser.newContext({viewport:{width:phone?360:1440,height:phone?800:960}, colorScheme:dark?'dark':'light',recordVideo:{dir:root,size:{width:phone?360:1440,height:phone?800:960}}});
  const p = await context.newPage();
  const errors=[], requests=[];
  p.on('pageerror',e=>errors.push(e.message));
  p.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
  p.on('request',r=>requests.push(new URL(r.url()).pathname));
  const assert=(value,message)=>{if(!value)throw new Error(message);};
  const checkWidth=async()=>assert(await p.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Document overflow');
  const send=async(text,watch=false)=>{
    await p.getByRole('textbox',{name:'Message Budget Buddy'}).fill(text);
    await p.getByRole('button',{name:'Send message',exact:true}).click();
    if(watch){await p.locator('[data-plan-id="o1"]').waitFor({state:'attached'});assert(await p.getByRole('button',{name:'Stop reply',exact:true}).isVisible(),'Plan arrived after reply');}
    await p.getByRole('button',{name:'Stop reply',exact:true}).waitFor({state:'hidden'});
  };
  const openPlan=async()=>{if(phone)await p.getByRole('button',{name:/Your plan ·/}).click();};
  const closePlan=async()=>{if(phone)await p.getByRole('button',{name:'Close plan',exact:true}).click();};
  const accept=async(id)=>{await p.locator(`[data-plan-id="${id}"]`).getByRole('button',{name:'Accept',exact:true}).click();await p.locator(`[data-plan-id="${id}"]`).getByRole('button',{name:'Reconsider',exact:true}).waitFor({state:'visible'});};
  await p.goto('http://localhost:3208');
  await p.getByRole('textbox',{name:'Message Budget Buddy'}).isEnabled().then(async ready=>{if(!ready)await p.waitForFunction(()=>!document.querySelector('#advisor-message').disabled);});
  assert((await p.locator('body').innerText()).includes('AI tech advisor run by Kenac Computer Systems'),'Opening missing');
  assert(await p.getByRole('link',{name:'How we handle data'}).getAttribute('href')==='/privacy','Privacy footer missing');
  assert(requests.filter(r=>r==='/api/plan').length===1,'Repeated initial resume');
  assert(await p.getByLabel('Work email',{exact:true}).count()===0,'Early contact form');
  await p.screenshot({path:`${root}/${review}-opening.png`});
  await send("We're about 180 staff, head office and four new branches next year. The board wants fewer outages.",true);
  await send('Mostly power; ZESA cuts.');
  await openPlan();await checkWidth();
  assert(await p.locator('[data-plan-id="i7"]').getByText('Spotted',{exact:true}).isVisible(),'Firewall not spotted');
  await accept('o1');await accept('o2');await accept('i3');await accept('i7');
  const sd=p.locator('[data-plan-id="i4"]');
  await sd.getByRole('button',{name:'Not now',exact:true}).click();
  await sd.getByLabel('Add a reason',{exact:false}).fill('Power comes first; review connectivity after opening.');
  await sd.getByRole('button',{name:'Set aside',exact:true}).click();
  await sd.getByText(/Set aside · Power comes first/).waitFor();
  await accept('l5');await accept('l6');await accept('l8');
  await closePlan();await send('What will the solar cost?');
  assert((await p.locator('body').innerText()).includes('That line stays Unpriced'),'Invented demo price');
  await openPlan();
  const solar=p.locator('[data-plan-id="l5"]');
  await solar.getByRole('button',{name:'Add my own estimate',exact:true}).click();
  await solar.getByLabel('Unit price',{exact:true}).fill('3500');
  await solar.getByRole('button',{name:'Use estimate',exact:true}).click();
  await solar.getByText('Own estimate',{exact:true}).waitFor();
  await p.locator('[aria-label="US$14,000 so far"]').first().waitFor();
  await p.screenshot({path:`${root}/${review}-plan.png`});
  await checkWidth();await closePlan();
  await send("let's wrap up");
  await p.getByLabel('Work email',{exact:true}).waitFor();
  assert(await p.getByRole('checkbox',{name:'Email me my plan and the Excel file',exact:true}).isChecked(),'Email default');
  assert(!await p.getByRole('checkbox',{name:'Kenac may contact me about items I choose to share',exact:true}).isChecked(),'Contact default');
  await p.screenshot({path:`${root}/${review}-wrap-up.png`});
  await p.getByLabel('Name',{exact:true}).fill('Synthetic reviewer');
  await p.getByLabel('Work email',{exact:true}).fill('reviewer@example.test');
  await p.getByLabel('Organisation',{exact:true}).fill('Synthetic demo organisation');
  await p.locator('select[name=role]').selectOption('CIO');
  await p.getByRole('button',{name:'Save my plan',exact:true}).click();
  await p.getByText('Saved. Keep this link to come back:',{exact:true}).waitFor();
  const returnUrl=await p.locator('a[href*="/r/"]').first().getAttribute('href');
  const downloadPromise=p.waitForEvent('download');
  await p.getByRole('link',{name:'Download Excel file',exact:true}).first().click();
  const download=await downloadPromise;await download.saveAs(`${root}/${review}.xlsx`);
  assert(download.suggestedFilename()==='ICT-plan-2027.xlsx','Download name');
  await p.getByRole('button',{name:'Choose items to share',exact:true}).click();
  await p.getByRole('checkbox',{name:/Share with Kenac.*Solar \+ UPS kit/}).check();
  assert(!await p.getByRole('checkbox',{name:'Include my budget for this item',exact:true}).isChecked(),'Allocation default');
  await p.screenshot({path:`${root}/${review}-sharing.png`});
  await checkWidth();
  await p.getByRole('button',{name:'Share 1 item with Kenac',exact:true}).click();
  await p.getByText('Shared 1 item with Kenac. You can withdraw them here at any time.',{exact:true}).waitFor();
  const operator=await context.request.get('http://localhost:3208/kenac',{headers:{Authorization:'Bearer T8_demo_operator_token_abcdefghijklmnopqrstuvwxyz'}});
  const html=await operator.text();assert(operator.status()===200&&html.includes('Solar + UPS kit, per branch'),'Shared row missing');
  assert(!html.includes('14,000')&&!html.includes('3500')&&!html.includes('reviewer@example.test'),'Allocation or contact leaked');
  const returned=await browser.newContext({viewport:{width:1440,height:960},colorScheme:'dark'});
  const r=await returned.newPage();await r.goto(returnUrl);await r.getByText('Welcome back. Your plan and the decisions we made are here.',{exact:true}).waitFor();
  const restored=await (await returned.request.get('http://localhost:3208/api/plan')).json();
  assert(restored.saved&&restored.plan.lines.find(l=>l.id==='l5').price.unitPrice==='3500','Return lost plan');
  assert(restored.plan.initiatives.find(i=>i.id==='i4').dismissReason.includes('Power comes first'),'Decision lost');
  await r.screenshot({path:`${root}/${review}-return.png`});await returned.close();
  await p.getByRole('checkbox',{name:/Share with Kenac.*Solar \+ UPS kit/}).uncheck();
  await p.getByRole('button',{name:'Keep all items private',exact:true}).click();
  await p.getByText('All items are private. Kenac can no longer view them here.',{exact:true}).waitFor();
  const owner=await (await context.request.get('http://localhost:3208/api/plan')).json();
  assert(!owner.plan.lines.find(l=>l.id==='l5').sharedWithKenac,'Withdrawal failed');
  await p.getByRole('link',{name:'How we handle data',exact:true}).click();
  await p.getByRole('button',{name:'Delete my plan',exact:true}).click();
  await p.getByRole('button',{name:'Keep my plan',exact:true}).click();
  assert((await context.request.get('http://localhost:3208/api/plan')).status()===200,'Cancel deleted plan');
  await p.evaluate(()=>localStorage.setItem('bb-theme',document.documentElement.classList.contains('hf-theme-dark')?'dark':'light'));
  await p.getByRole('button',{name:'Delete my plan',exact:true}).click();
  await p.getByRole('button',{name:'Delete permanently',exact:true}).click();
  await p.getByText('Your plan was deleted. You can start a new conversation.',{exact:true}).waitFor();
  await checkWidth();
  assert((await context.request.get('http://localhost:3208/api/plan')).status()===204,'Session survived deletion');
  assert(await p.evaluate(()=>Object.keys(localStorage).filter(k=>k.startsWith('bb-draft')).length)===0,'Draft survived deletion');
  assert(await p.evaluate(()=>!!localStorage.getItem('bb-theme')),'Theme deleted');
  const expired=await context.request.get(returnUrl,{maxRedirects:0});assert(expired.headers().location.includes('link-expired'),'Return credential survived deletion');
  assert(errors.length===0,`Browser errors: ${errors.join('; ')}`);
  const video=await p.video().path();await context.close();
  return {review,passed:true,initialResumeRequests:1,browserErrors:errors,download:download.suggestedFilename(),video};
}
