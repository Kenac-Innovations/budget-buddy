// Generates src/styles/tokens.css from the vendored Humaflow design tokens.
// Run after updating design-system/humaflow/tokens.json: `pnpm tokens`.
import { readFileSync, writeFileSync } from "node:fs";

const tokens = JSON.parse(readFileSync(new URL("../design-system/humaflow/tokens.json", import.meta.url), "utf8"));

const ref = (v) => String(v).replace(/\{([\w-]+)\}/g, "var(--$1)");
const light = [];
const dark = [];

function add(name, value) {
  if (value && typeof value === "object") {
    light.push(`  --${name}: ${ref(value.light)};`);
    if (value.dark !== undefined) dark.push(`  --${name}: ${ref(value.dark)};`);
  } else {
    light.push(`  --${name}: ${ref(value)};`);
  }
}

for (const t of tokens.color.tokens) add(t.name, t.value);
for (const t of tokens.spacing.tokens) add(t.name, t.value);
for (const t of tokens.radius.tokens) add(t.name, t.value);
for (const t of tokens.shadow.tokens) add(t.name, t.value);
for (const t of tokens.zIndex.tokens) add(t.name, t.value);

const css = `/* Generated by scripts/build-tokens.mjs from design-system/humaflow/tokens.json (${tokens.meta.repo} ${tokens.meta.ref}). Do not edit. */
:root {
${light.join("\n")}
}

.hf-theme-dark {
  color-scheme: dark;
${dark.join("\n")}
}
`;
writeFileSync(new URL("../src/styles/tokens.css", import.meta.url), css);
console.log(`tokens.css: ${light.length} light, ${dark.length} dark`);
